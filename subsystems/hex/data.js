// Латиница и кириллица в координатах выглядят одинаково; приводим к латинице.
const CYR = { "А": "A", "В": "B", "С": "C", "Е": "E", "Н": "H" };
export function normCoord(raw) {
  const s = String(raw ?? "").trim().toUpperCase().replace(/[\s\-–—]/g, "");
  if (!s) return "";
  const letter = CYR[s[0]] ?? s[0];
  const num = Number(s.slice(1));
  if (!/^[A-H]$/.test(letter) || !Number.isInteger(num) || num < 1 || num > 19) return null;
  return `${letter}${num}`;
}

